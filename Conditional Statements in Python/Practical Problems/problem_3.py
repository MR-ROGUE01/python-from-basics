'''Problem 1: Check if a student is pass/fail in exam.
This program determines whether a student has passed an exam.
It takes the student's marks as input and uses an if-else statement to 
check if the marks are 40 or above, which is considered the passing score.
'''
marks = int(input("Enter the student's marks: "))
if marks >= 40:
    print("The student has passed.")
else:
    print("The student has failed.")
    
    
